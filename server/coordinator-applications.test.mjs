test('applications isolate accounts and approval requires independent MFA reviewer, verified pilot and membership',{skip:!process.env.DATABASE_TEST_URL},async t=>{
 const f=await retrievalFixture();t.after(()=>f.close());
 const now=Math.floor(Date.now()/1000),org=randomUUID(),parent=randomUUID();
 const own=(sub,input)=>f.as(sub,()=>runApplicationCommand(f.db,input));
 const review=(sub,input)=>f.as(sub,()=>runAsCoordinatorActor(sub,{administrator:true,issuedAt:now},()=>runApplicationCommand(f.db,input)));
 const coordinator=(sub,input,admin=false)=>f.as(sub,()=>runAsCoordinatorActor(sub,{administrator:admin,issuedAt:now},()=>runCoordinatorCommand(f.db,input)));
 await own('applicant',{...submission,verifiedEmail:'synthetic@example.org'});
 let application=(await own('applicant',{action:'application-status'})).application;
 assert.equal(application.status,'pending');
 assert.equal((await own('other',{action:'application-status'})).application,null);
 await assert.rejects(f.as('applicant',()=>f.db.query('SELECT * FROM origen_coordinator_applications')),{code:'42501'});
 for(const table of ['origen_institution_members','origen_coordinator_profiles','origen_coordinator_codes'])assert.equal((await f.owner.query(`SELECT count(*)::int n FROM ${table}`)).rows[0].n,0);
 await own('applicant',{...submission,displayName:'Retry does not change review data',verifiedEmail:'synthetic@example.org'});
 assert.equal((await own('applicant',{action:'application-status'})).application.id,application.id);
 await assert.rejects(own('applicant',{action:'applications'}),{code:'42501'});
 await assert.rejects(review('applicant',{action:'decline-application',id:application.id,reviewNote:'Self approval'}),/independent_review_required/);
 assert.equal((await review('reviewer',{action:'applications'})).applications.length,1);
 for(const [id,name] of [[org,'Community Organization'],[parent,'Parent Organization']])await f.owner.query('INSERT INTO origen_institutions(id,slug,draft) VALUES($1,$2,$3)',[id,id,{name}]);
 const approve={action:'approve-application',id:application.id,institutionId:org,reviewNote:'Affiliation checked independently.'};
 await assert.rejects(review('reviewer',approve),/organization_verification_required/);
 await f.owner.query("UPDATE origen_institutions SET verification_status='verified'");
 await coordinator('reviewer',{action:'approve-organization',id:org},true);
 await assert.rejects(review('reviewer',approve),/application_membership_required/);
 await f.owner.query("INSERT INTO origen_institution_members VALUES($1,'applicant','outreach')",[org]);
 await f.owner.query("INSERT INTO origen_institution_representatives(auth0_subject,first_name,work_email,job_role) VALUES('owner','Owner','owner@example.org','Owner')");
 await f.owner.query("INSERT INTO origen_institution_members VALUES($1,'owner','owner')",[org]);
 await assert.rejects(review('owner',approve),/independent_review_required/);
 await f.owner.query("INSERT INTO origen_staff_access_controls(subject_hash,blocked) VALUES($1,true)",[staffHash('applicant')]);
 await assert.rejects(review('reviewer',approve),{code:'42501'});
 await f.owner.query('DELETE FROM origen_staff_access_controls WHERE subject_hash=$1',[staffHash('applicant')]);
 await review('reviewer',approve);
 assert.equal((await own('applicant',{action:'application-status'})).application.status,'approved');
 assert.equal((await coordinator('applicant',{action:'profile',id:org})).profile.displayName,submission.displayName);
 for(const table of ['origen_coordinator_codes','origen_binder_connections','origen_binder_share_grants'])assert.equal((await f.owner.query(`SELECT count(*)::int n FROM ${table}`)).rows[0].n,0);
 await assert.rejects(review('reviewer',approve),/application_changed/);
 await own('applicant',{action:'withdraw-application',id:application.id});
 assert.equal((await own('applicant',{action:'application-status'})).application.status,'approved');
 await coordinator('owner',{action:'disable-member',id:org,subject:'applicant'});
 await assert.rejects(coordinator('applicant',{action:'profile',id:org}),{code:'42501'});
 await assert.rejects(review('reviewer',approve),/application_changed/);
 await own('declined',{...submission,verifiedEmail:'declined@example.org'});
 const declined=(await own('declined',{action:'application-status'})).application;
 await review('reviewer',{action:'decline-application',id:declined.id,reviewNote:'Please confirm your organization.'});
 assert.equal((await own('declined',{action:'application-status'})).application.reviewNote,'Please confirm your organization.');
 await own('declined',{action:'withdraw-application',id:declined.id});
 assert.equal((await own('declined',{action:'application-status'})).application,null);
 await own('declined',{...submission,verifiedEmail:'declined@example.org'});
 const lifecycle=createLifecycleRepository(f.db);
 const exported=await f.as('declined',()=>lifecycle('declined',{action:'export'}));
 assert.equal(exported.coordinatorApplication.application.email,'declined@example.org');
 assert.ok(!JSON.stringify(exported).includes('synthetic@example.org'));
 await f.as('declined',()=>lifecycle('declined',{action:'delete',confirmation:'DELETE'}));
 assert.equal((await f.owner.query("SELECT count(*)::int n FROM origen_coordinator_applications WHERE auth0_subject='declined'")).rows[0].n,0,'Account erasure cascades to application');
 assert.equal((await f.owner.query("SELECT count(*)::int n FROM origen_coordinator_application_controls WHERE auth0_subject='declined'")).rows[0].n,0,'Account erasure cascades to review controls');
 await assert.rejects(own('declined',{...submission,verifiedEmail:'declined@example.org'}),/account_closed/);

 await t.test('HTTP rejects forged email and permission; applicants do not need staff MFA',async()=>{
  let identity={sub:'http-applicant',iat:now},verified=true,matched=true;
  const env={ORIGEN_COORDINATOR_ACCOUNTS:'true',AUTH0_DOMAIN:'synthetic.auth0.com'};
  const handler=createCoordinatorHandler(f.db,env,async()=>({ok:true,json:async()=>({sub:matched?identity.sub:'someone-else',email:'trusted@example.org',email_verified:verified})}));
  const institutions=createInstitutionHandler(f.db,env);
  const server=createServer((req,res)=>{req.origenIdentity=identity;req.origenAuthorized=true;void runAsAccount(identity,()=>handler(req,res,()=>institutions(req,res,()=>{res.writeHead(404);res.end();})));});
  await new Promise(r=>server.listen(0,'127.0.0.1',r));
  const send=body=>fetch(`http://127.0.0.1:${server.address().port}/api/coordinator-access`,{method:'POST',headers:{'Content-Type':'application/json',Authorization:'Bearer synthetic'},body:JSON.stringify(body)});
  try{
   verified=false;assert.equal((await send({...submission,email_verified:true})).status,403);
   verified=true;matched=false;assert.equal((await send(submission)).status,403);
   matched=true;
   const response=await send({...submission,verifiedEmail:'forged@example.org',subject:'applicant',status:'approved'});
   assert.equal(response.status,200);const submitted=(await response.json()).application;assert.equal(submitted.email,'trusted@example.org');
   const signupStatus=()=>fetch(`http://127.0.0.1:${server.address().port}/api/institutions`,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({action:'signup-status',applicationId:submitted.id})});
   assert.equal((await signupStatus()).status,403,'Signup recovery still requires staff MFA');
   identity={...identity,[MFA_TIME_CLAIM]:now,[AUTH_TIME_CLAIM]:now};
   const recovered=await signupStatus();assert.equal(recovered.status,200);assert.equal((await recovered.json()).organization,null);
   env.ORIGEN_COORDINATOR_ACCOUNTS='false';assert.equal((await signupStatus()).status,503);env.ORIGEN_COORDINATOR_ACCOUNTS='true';
   identity={sub:'http-applicant',iat:now};
   const access=await fetch(`http://127.0.0.1:${server.address().port}/api/institutions`,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({action:'access'})});
   assert.equal(access.status,200);const workspace=await access.json();assert.equal(workspace.coordinatorApplicationStatus,'pending');assert.deepEqual(workspace.memberships,[]);assert.equal(workspace.hasPersonalAccount,false);
   assert.equal((await send({action:'applications',administrator:true})).status,403);
   identity={sub:'reviewer',iat:now,permissions:['manage:institutions']};
   assert.equal((await send({action:'applications'})).status,403);
   identity={...identity,[MFA_TIME_CLAIM]:now,[AUTH_TIME_CLAIM]:now};
   assert.equal((await send({action:'applications'})).status,200);
   env.ORIGEN_COORDINATOR_ACCOUNTS='false';assert.equal((await send({action:'application-status'})).status,503);
  }finally{await new Promise(r=>server.close(r));}
 });
});
